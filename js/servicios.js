const serviceModal = document.getElementById("service-modal")
const modalOverlay = document.getElementById("modal-overlay")
const modalClose = document.getElementById("modal-close")
const modalContent = document.getElementById("modal-content")
const serviceCards = document.querySelectorAll(".service-card")

// Open modal function
function openServiceModal(serviceKey) {
  const service = servicesData[serviceKey]
  if (!service || !serviceModal) return

  // Generate modal content
  let modalHTML = `
        <div class="modal-header">
            <img src="${service.image}" alt="${service.title}" class="modal-header__image">
            <h2 class="modal-header__title">${service.title}</h2>
            <p class="modal-header__subtitle">${service.subtitle}</p>
        </div>
        
        <div class="modal-body">
            <div class="modal-section">
                <h3 class="modal-section__title">
                    <span>📋</span>
                    Descripción del Servicio
                </h3>
                <div class="modal-section__content">
                    ${service.content}
                </div>
            </div>
    `

  if (service.highlights) {
    modalHTML += `
            <div class="modal-highlights">
                <h4 class="modal-highlights__title">Puntos Destacados</h4>
                <ul class="modal-highlights__list">
                    ${service.highlights.map((highlight) => `<li class="modal-highlights__item">${highlight}</li>`).join("")}
                </ul>
            </div>
        `
  }

  modalHTML += `
        </div>
        
        <div class="modal-footer">
            <a href="https://wa.me/5491162601611?text=Hola! Me interesa el servicio de ${service.title}" 
               class="modal-btn modal-btn--primary" target="_blank">
                <span>📅</span>
                Reservar Turno
            </a>
            <button class="modal-btn modal-btn--secondary" onclick="closeServiceModal()">
                <span>←</span>
                Volver
            </button>
        </div>
    `
    
  // Insert content and show modal
  modalContent.innerHTML = modalHTML
  serviceModal.classList.add("active")
  document.body.classList.add("modal-open")

  // Add entrance animation
  setTimeout(() => {
    const modalContainer = serviceModal.querySelector(".service-modal__content")
    if (modalContainer) {
      modalContainer.style.transform = "scale(1)"
    }
  }, 50)
}

// Close modal function
function closeServiceModal() {
  if (!serviceModal) return

  serviceModal.classList.remove("active")
  document.body.classList.remove("modal-open")

  // Clear content after animation
  setTimeout(() => {
    if (modalContent) {
      modalContent.innerHTML = ""
    }
  }, 300)
}

// Event listeners for service cards
if (serviceCards.length > 0) {
  serviceCards.forEach((card) => {
    const button = card.querySelector(".service-card__btn")
    const serviceKey = card.getAttribute("data-service")

    if (button && serviceKey) {
      button.addEventListener("click", (e) => {
        e.preventDefault()
        openServiceModal(serviceKey)
      })
    }

    // Also allow clicking the entire card
    card.addEventListener("click", (e) => {
      // Don't trigger if clicking the button specifically
      if (!e.target.closest(".service-card__btn")) {
        openServiceModal(serviceKey)
      }
    })
  })
}

// Close modal event listeners
if (modalClose) {
  modalClose.addEventListener("click", closeServiceModal)
}

if (modalOverlay) {
  modalOverlay.addEventListener("click", closeServiceModal)
}

// Keyboard navigation
document.addEventListener("keydown", (e) => {
  if (serviceModal && serviceModal.classList.contains("active")) {
    if (e.key === "Escape") {
      closeServiceModal()
    }
  }
})

